const TONES: ListingImageTone[] = ["gold", "amber", "sky", "slate", "rose"];

type ShowcaseSeed = {
  key: string;
  categoryId: string;
  subcategory: string;
  title: string;
  titleEnglish: string;
  description: string;
  descriptionEnglish: string;
  price: number;
  emirate: string;
  city: string;
  area: string;
  condition: ListingCondition;
  categorySpecs?: CategorySpecs;
  carSpecs?: Listing["carSpecs"];
  realEstateSpecs?: Listing["realEstateSpecs"];
  electronicsSpecs?: Listing["electronicsSpecs"];
  features?: string[];
  deliveryOption?: Listing["deliveryOption"];
  mediaCategory?: ImageFallbackCategory;
};

function mediaFor(categoryId: string, slug: string): { imageUrl: string; images: string[] } {
  const key = (categoryId in {
    cars: 1,
    "real-estate": 1,
    electronics: 1,
    mobiles: 1,
    furniture: 1,
    jobs: 1,
    fashion: 1,
    services: 1,
    pets: 1,
    kids: 1,
    books: 1,
    sports: 1,
    food: 1,
  }
    ? categoryId
    : "default") as ImageFallbackCategory;
  const images = galleryFromPool(key, slug, 4);
  return { imageUrl: images[0] ?? "", images };
}

function withDemoCopy(arabic: string, english: string): { description: string; descriptionEnglish: string } {
  return {
    description: `${arabic}\n\n${DEMO_FOOTER_AR}`,
    descriptionEnglish: `${english}\n\n${DEMO_FOOTER_EN}`,
  };
}

function buildListing(seed: ShowcaseSeed, index: number): Listing {
  const slug = `showcase-${seed.key}`;
  const media = mediaFor(seed.mediaCategory ?? seed.categoryId, slug);
  const copy = withDemoCopy(seed.description, seed.descriptionEnglish);
  const postedAt = new Date(Date.UTC(2026, 8, 8, 12, 0, 0) - index * 6 * 60 * 60 * 1000).toISOString();

  return {
    id: `showcase-${seed.categoryId}-${String(index + 1).padStart(2, "0")}`,
    slug,
    title: seed.title,
    titleEnglish: seed.titleEnglish,
    description: copy.description,
    descriptionEnglish: copy.descriptionEnglish,
    categoryId: seed.categoryId,
    subcategory: seed.subcategory,
    city: seed.city,
    emirate: seed.emirate,
    area: seed.area,
    country: "الإمارات العربية المتحدة",
    price: seed.price,
    currency: "AED",
    condition: seed.condition,
    status: "active",
    isFeatured: false,
    isPremium: false,
    views: 0,
    imageUrl: media.imageUrl,
    images: media.images,
    seller: { ...SHOWCASE_SELLER },
    imageTone: TONES[index % TONES.length],
    isDemo: true,
    source: SHOWCASE_SOURCE,
    escrowAvailable: false,
    verifiedSeller: false,
    postedAt,
    contactMethod: "chat",
    deliveryOption: seed.deliveryOption ?? "both",
    negotiable: false,
    categorySpecs: seed.categorySpecs,
    carSpecs: seed.carSpecs,
    realEstateSpecs: seed.realEstateSpecs,
    electronicsSpecs: seed.electronicsSpecs,
    features: seed.features,
  };
}

