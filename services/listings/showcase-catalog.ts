export function genericShowcaseListing(input: {
  categoryId: string;
  categoryName: string;
  subcategory?: string;
  index: number;
}): Listing {
  const key = `${input.categoryId}-generic-${input.index + 1}`;
  const subcategory = input.subcategory?.trim() || input.categoryName;
  return buildListing(
    {
      key,
      categoryId: input.categoryId,
      subcategory,
      title: `نموذج ${input.categoryName} — معرض تجريبي`,
      titleEnglish: `${input.categoryName} showcase example`,
      description: `إعلان توضيحي لقسم ${input.categoryName} حتى لا تظهر الصفحة فارغة.`,
      descriptionEnglish: `An illustrative listing for the ${input.categoryName} category so the page is not empty.`,
      price: 100,
      emirate: "دبي",
      city: "دبي",
      area: "وسط المدينة",
      condition: "used",
    },
    80 + input.index,
  );
}
